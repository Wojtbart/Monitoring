const STORAGE_KEY = "ui_lang";

// Nagłówek dla backendu (back/i18n.py::current_lang) — ustawiany jako
// axios default, więc KAŻDY request (w każdym pliku, bez osobnego wiring)
// dostaje aktualny język automatycznie.
function applyAxiosHeader(lang) {
    axios.defaults.headers.common["Accept-Language"] = lang;
}

// Ustawione OD RAZU przy imporcie modułu (nie w efekcie Reacta) — inaczej
// pierwsze requesty stron, które odpalają się w swoim własnym useEffect,
// mogłyby wystartować przed efektem Providera i polecieć bez nagłówka.
const initialLang = localStorage.getItem(STORAGE_KEY) || "pl";
applyAxiosHeader(initialLang);

const LangContext = createContext({ lang: initialLang, setLang: () => {}, t: k => k });

export function LangProvider({ children }) {
    const [lang, setLangState] = useState(initialLang);

    const setLang = (next) => {
        setLangState(next);
        localStorage.setItem(STORAGE_KEY, next);
        applyAxiosHeader(next);
    };

    const t = (key) => DICT[lang]?.[key] ?? DICT.pl[key] ?? key;

    return (
        <LangContext.Provider value={{ lang, setLang, t }}>
            {children}
        </LangContext.Provider>
    );
}

export const useLang = () => useContext(LangContext);
